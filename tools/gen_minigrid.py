def build_clues_and_words():
    clues = {}
    curated_by_len = {3: [], 4: [], 5: []}
    for length, table in ((3, WORDS_3), (4, WORDS_4), (5, WORDS_5)):
        for word, clue in table.items():
            if len(word) != length or not word.isalpha() or word != word.upper():
                print(f"warning: dropping malformed entry {word!r}", file=sys.stderr)
                continue
            clues[word] = clue
            curated_by_len[length].append(word)
    return clues, curated_by_len


CLUES, CURATED_BY_LEN = build_clues_and_words()
CURATED_SET = set(CLUES.keys())


# The generator fills ONLY from the curated, hand-clued word set above.
# An earlier version fell back to the full shared wordlist.txt (ENABLE) for
# slots the curated list couldn't satisfy; a discovery run of that fallback
# surfaced a slur among the candidates. ENABLE is a Scrabble word list, not a
# vetted "fine to show a stranger on a puzzle page" list, and there is no
# cheap way to filter it down to that bar. So there is no fallback: every
# answer that can ever appear comes from CLUES, which this file's author
# wrote and can vouch for. See enumerate_solutions and main for how the bank
# is built and validated from this vocabulary alone.
FALLBACK_BY_LEN = {3: [], 4: [], 5: []}
WORDS_BY_LEN = {length: CURATED_BY_LEN[length] for length in (3, 4, 5)}


def build_position_index():
    """index[length][position][letter] -> tuple of candidate words.

    Lets domain filtering intersect index sets instead of rescanning every
    word in the pool at every backtracking node.
    """
    index = {}
    for length, words in WORDS_BY_LEN.items():
        by_pos = [{} for _ in range(length)]
        for w in words:
            for pos, ch in enumerate(w):
                by_pos[pos].setdefault(ch, []).append(w)
        index[length] = [{ch: frozenset(ws) for ch, ws in pos_map.items()} for pos_map in by_pos]
    return index


POSITION_INDEX = build_position_index()

