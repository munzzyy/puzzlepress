CORNERS = {"tl": (0, 0), "tr": (0, 4), "bl": (4, 0), "br": (4, 4)}
TEMPLATES = {
    0: [frozenset()],
    2: [frozenset({CORNERS["tl"], CORNERS["br"]}), frozenset({CORNERS["tr"], CORNERS["bl"]})],
    4: [frozenset(CORNERS.values())],
}


def segments_ok(is_block, length, index_range, cell_at):
    """A row or column is valid if every maximal open run is length 0 or >= 3."""
    run = 0
    for i in index_range:
        if is_block(*cell_at(i)):
            if 0 < run < 3:
                return False
            run = 0
        else:
            run += 1
    return not (0 < run < 3)


def validate_template(blocks):
    is_block = lambda r, c: (r, c) in blocks
    for r in range(SIZE):
        if not segments_ok(is_block, SIZE, range(SIZE), lambda c, r=r: (r, c)):
            return False
    for c in range(SIZE):
        if not segments_ok(is_block, SIZE, range(SIZE), lambda r, c=c: (r, c)):
            return False
    return True


for _count, _variants in TEMPLATES.items():
    for _blocks in _variants:
        assert validate_template(_blocks), f"template with {_count} blocks failed validation"


def compute_slots(blocks):
    """Mirrors games/minigrid/core.js parsePuzzle: same numbering algorithm."""
    is_block = lambda r, c: (r, c) in blocks
    slots = []

    for r in range(SIZE):
        c = 0
        while c < SIZE:
            if is_block(r, c):
                c += 1
                continue
            start = c
            while c < SIZE and not is_block(r, c):
                c += 1
            length = c - start
            if length >= 3:
                cells = [(r, cc) for cc in range(start, c)]
                slots.append({"dir": "across", "row": r, "col": start, "length": length, "cells": cells})

    for c in range(SIZE):
        r = 0
        while r < SIZE:
            if is_block(r, c):
                r += 1
                continue
            start = r
            while r < SIZE and not is_block(r, c):
                r += 1
            length = r - start
            if length >= 3:
                cells = [(rr, c) for rr in range(start, r)]
                slots.append({"dir": "down", "row": start, "col": c, "length": length, "cells": cells})

    starts = {(s["row"], s["col"]) for s in slots}
    numbering = {}
    n = 0
    for r in range(SIZE):
        for c in range(SIZE):
            if is_block(r, c):
                continue
            if (r, c) in starts:
                n += 1
                numbering[(r, c)] = n
    for s in slots:
        s["number"] = numbering[(s["row"], s["col"])]
    return slots


def enumerate_solutions(slots, rng, cap=2000, node_budget=2_000_000, time_budget=40.0):
    """Depth-first search that keeps going past the first solution, collecting
    every complete filling it finds (up to cap) in one shared search tree.

    A restart-based solver (try random word order, give up after a node/time
    budget, shuffle, try again) turned out to be a poor fit here: with 6
    mutually-crossing 5-letter slots, valid fillings are a small, oddly
    shaped island in the search space, so *independent* random restarts keep
    re-finding the same easy handful and burning their whole budget on the
    rest. A single DFS that doesn't stop at the first answer explores that
    same island exhaustively and finds every solution in it far faster than
    restarting ever could -- see the module's build history for the numbers
    (hundreds of complete fillings in single-digit seconds).
    """
    n = len(slots)
    assignment = {}
    grid = {}
    used_words = set()
    found = []
    nodes = 0
    deadline = time.monotonic() + time_budget

    order = {}
    for i, s in enumerate(slots):
        pool = list(CURATED_BY_LEN[s["length"]])
        rng.shuffle(pool)
        order[i] = pool
    rank = {i: {w: k for k, w in enumerate(pool)} for i, pool in order.items()}

    def domain(i):
        s = slots[i]
        idx = POSITION_INDEX[s["length"]]
        candidates = None
        for local_pos, (r, c) in enumerate(s["cells"]):
            letter = grid.get((r, c))
            if letter is None:
                continue
            bucket = idx[local_pos].get(letter)
            if not bucket:
                return []
            candidates = bucket if candidates is None else (candidates & bucket)
            if not candidates:
                return []
        candidates = list(candidates) if candidates is not None else list(WORDS_BY_LEN[s["length"]])
        # No answer word may appear twice in one puzzle (once across, once
        # down): it would hand a player half of one clue for free.
        candidates = [w for w in candidates if w not in used_words]
        candidates.sort(key=lambda w: rank[i][w])
        return candidates

    def dfs():
        nonlocal nodes
        if len(found) >= cap or nodes > node_budget or time.monotonic() > deadline:
            return
        nodes += 1
        if len(assignment) == n:
            found.append(dict(assignment))
            return
        best_i, best_dom = None, None
        for i in range(n):
            if i in assignment:
                continue
            d = domain(i)
            if best_dom is None or len(d) < len(best_dom):
                best_i, best_dom = i, d
            if not d:
                return
        for w in best_dom:
            placed = []
            conflict = False
            for (r, c), ch in zip(slots[best_i]["cells"], w):
                if (r, c) in grid:
                    if grid[(r, c)] != ch:
                        conflict = True
                        break
                else:
                    grid[(r, c)] = ch
                    placed.append((r, c))
            if conflict:
                for p in placed:
                    del grid[p]
                continue
            assignment[best_i] = w
            used_words.add(w)
            dfs()
            del assignment[best_i]
            used_words.discard(w)
            for p in placed:
                del grid[p]
            if len(found) >= cap or time.monotonic() > deadline:
                return

    dfs()
    return found


def assignment_to_puzzle(blocks, slots, assignment):
    grid_rows = []
    for r in range(SIZE):
        row = []
        for c in range(SIZE):
            if (r, c) in blocks:
                row.append("#")
            else:
                slot_i = next(i for i, s in enumerate(slots) if (r, c) in s["cells"])
                word = assignment[slot_i]
                local = next(k for k, cell in enumerate(slots[slot_i]["cells"]) if cell == (r, c))
                row.append(word[local])
        grid_rows.append("".join(row))

    clues = {"across": {}, "down": {}}
    for i, s in enumerate(slots):
        clues[s["dir"]][str(s["number"])] = CLUES[assignment[i]]
    return {"grid": grid_rows, "clues": clues}


def transpose_puzzle(puzzle):
    """Swaps rows/columns. Every one of this game's block templates is
    symmetric under transpose (see the module docstring), and swapping
    letters at (r, c) with (c, r) turns each across entry into a down entry
    reading the exact same letters in the exact same order, and vice versa.
    So this always yields a second fully valid, distinct puzzle for free
    from the same solved grid, at no extra search cost.
    """
    grid = puzzle["grid"]
    t_grid = ["".join(grid[c][r] for c in range(SIZE)) for r in range(SIZE)]
    blocks = {(r, c) for r in range(SIZE) for c in range(SIZE) if t_grid[r][c] == "#"}
    slots = compute_slots(blocks)
    clues = {"across": {}, "down": {}}
    for s in slots:
        word = "".join(t_grid[r][c] for r, c in s["cells"])
        clues[s["dir"]][str(s["number"])] = CLUES[word]
    return {"grid": t_grid, "clues": clues}


def load_wordlist():
    words = set()
    with WORDLIST_PATH.open(encoding="utf-8") as f:
        for line in f:
            w = line.strip()
            if w:
                words.add(w.lower())
    return words


def validate_bank(puzzles, dictionary):
    assert len(puzzles) > 0, "bank is empty"
    seen = set()
    for i, p in enumerate(puzzles):
        grid = p["grid"]
        assert len(grid) == SIZE, f"puzzle {i}: grid must have {SIZE} rows"
        for row in grid:
            assert len(row) == SIZE, f"puzzle {i}: row length must be {SIZE}"
            for ch in row:
                assert ch == "#" or ("A" <= ch <= "Z"), f"puzzle {i}: bad char {ch!r}"

        sig = tuple(grid)
        assert sig not in seen, f"puzzle {i}: duplicate grid"
        seen.add(sig)

        blocks = {(r, c) for r in range(SIZE) for c in range(SIZE) if grid[r][c] == "#"}
        assert any(blocks == v for variants in TEMPLATES.values() for v in variants), (
            f"puzzle {i}: block pattern is not one of the proven-valid templates"
        )

        slots = compute_slots(blocks)
        by_dir = {"across": {}, "down": {}}
        for s in slots:
            assert s["length"] in (3, 4, 5), f"puzzle {i}: entry length {s['length']} out of range"
            word = "".join(grid[r][c] for r, c in s["cells"])
            assert word.lower() in dictionary, f"puzzle {i}: {word} is not in the shared wordlist"
            by_dir[s["dir"]][str(s["number"])] = word

        for direction in ("across", "down"):
            got_numbers = set(p["clues"][direction].keys())
            expect_numbers = set(by_dir[direction].keys())
            assert got_numbers == expect_numbers, (
                f"puzzle {i}: {direction} clue numbers {got_numbers} do not match grid slots {expect_numbers}"
            )
            for num, clue_text in p["clues"][direction].items():
                word = by_dir[direction][num]
                assert clue_text == CLUES[word], f"puzzle {i}: clue for {word} does not match the curated text"
                assert clue_text.strip() == clue_text and clue_text, f"puzzle {i}: clue for {word} is malformed"
                for bad in ("\u2014", "\u2013", "\u2026"):
                    assert bad not in clue_text, f"puzzle {i}: clue for {word} has a forbidden character"


def main():
    parser = argparse.ArgumentParser(description="Generate the Minigrid puzzle bank.")
    parser.add_argument("--seed", type=int, default=20260810)
    parser.add_argument("--count", type=int, default=90)
    parser.add_argument("--out", type=Path, default=OUT_PATH)
    parser.add_argument(
        "--cap-per-template",
        type=int,
        default=800,
        help="max complete fillings to collect per block template before moving on",
    )
    args = parser.parse_args()

    rng = random.Random(args.seed)
    dictionary = load_wordlist()

    t0 = time.monotonic()
    # Search the 4-corner template first: it's the least dense (four
    # length-3 entries instead of length-5), so it has by far the largest
    # solution space for a given curated word count. See enumerate_solutions.
    all_variants = [
        (count, blocks) for count in (4, 2, 0) for blocks in TEMPLATES[count]
    ]
    puzzles = []
    seen_grids = set()
    template_uses = {}

    for count, blocks in all_variants:
        slots = compute_slots(blocks)
        solutions = enumerate_solutions(slots, rng, cap=args.cap_per_template)
        rng.shuffle(solutions)
        for assignment in solutions:
            base = assignment_to_puzzle(blocks, slots, assignment)
            for candidate in (base, transpose_puzzle(base)):
                sig = tuple(candidate["grid"])
                if sig in seen_grids:
                    continue
                seen_grids.add(sig)
                puzzles.append(candidate)
                template_uses[count] = template_uses.get(count, 0) + 1
        print(
            f"template blocks={count}: {len(solutions)} fillings found "
            f"({time.monotonic() - t0:.1f}s elapsed)"
        )
        if len(puzzles) >= args.count * 2:
            break  # plenty of headroom; no need to search the remaining templates

    rng.shuffle(puzzles)
    puzzles = puzzles[: args.count]

    validate_bank(puzzles, dictionary)
    print(f"generated {len(puzzles)} puzzles in {time.monotonic() - t0:.1f}s")

    OUT = args.out
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as f:
        json.dump({"puzzles": puzzles}, f, indent=2, ensure_ascii=True)
        f.write("\n")

    print(f"wrote {len(puzzles)} puzzles to {OUT}")
    print(f"template block-count usage: {template_uses}")
    if len(puzzles) < args.count:
        print(f"warning: requested {args.count} but only produced {len(puzzles)}", file=sys.stderr)


if __name__ == "__main__":
    main()
