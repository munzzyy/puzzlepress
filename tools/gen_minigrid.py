"""
Deterministic generator for data/minigrid.json (stdlib only).

Grid math: a 5x5 grid where every entry must be length >= 3 and every open
cell must be "checked" (belongs to both an across and a down entry) can only
place blocks in its four corners. Proof: for a row of width 5, a single block
at column c splits it into runs of length c and 4-c; both must be 0 or >= 3,
which is only true for c=0 or c=4. Two blocks in one row only work at columns
0 and 4 together (leaving a middle run of exactly 3). The same holds for
columns. A block therefore has to satisfy both its row's rule and its
column's rule at once, which is only possible at (0,0), (0,4), (4,0), (4,4).
So there are exactly three symmetric block counts: 0, 2 (one diagonal pair),
or 4 (all corners). TEMPLATES below is the complete list, not a subset.

Fill strategy: rather than pull answers from the full wordlist (which would
mean auto-generated, unclued fill), every answer this generator can place
comes from CLUES, a hand-written word -> clue dictionary. That keeps the
"every clue must match its answer" rule trivially true and puts the quality
budget where the contract asks for it: the clues themselves. No word may
appear twice in one puzzle (once across, once down); see enumerate_solutions.

Search strategy: enumerate_solutions runs one exhaustive depth-first search
per block template and collects every complete filling it finds, instead of
the more obvious "random restart until something works" approach. With a
curated (not encyclopedic) word list, valid fillings for a fully-crossed
template are a small, oddly shaped island in the search space; independent
restarts kept rediscovering the same handful and burning their budget on the
rest, while a single search that keeps going past the first hit explores
that island completely and finds every solution in it. transpose_puzzle then
doubles the yield for free: swapping rows and columns turns every across
entry into a down entry reading the same letters in the same order, so it's
always a second valid, distinct puzzle from the same fill.
"""

